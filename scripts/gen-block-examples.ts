// Finds the worked examples of the two block lessons with the real engine and prints src/data/block-examples.ts.
// Run: bun run scripts/gen-block-examples.ts > src/data/block-examples.ts
import { applyAlg, solvedState } from "../shared/cube";
import { FIRST_BLOCK_PLAN, SECOND_BLOCK_PLAN, solveInStages } from "../shared/block-stages";
import { randomSecondBlockScramble } from "../src/lib/scramble";

// small deterministic generator so the printed example can be reproduced
let seed = Number(process.argv[2] ?? 7);
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const pick = <T>(a: T[]) => a[Math.floor(rnd() * a.length)];

function faceScramble(n: number): string {
  const out: string[] = [];
  while (out.length < n) {
    const f = pick(["R", "L", "U", "D", "F", "B"]);
    if (out.length && out[out.length - 1][0] === f) continue;
    out.push(f + pick(["", "'", "2"]));
  }
  return out.join(" ");
}

// first block: a 20-move scramble whose three jobs each take 1 to 4 moves and 11 or fewer in all
let first: { scramble: string; jobs: string[] } | null = null;
for (let t = 0; t < 400 && !first; t++) {
  const scramble = faceScramble(20);
  const r = solveInStages(FIRST_BLOCK_PLAN, applyAlg(solvedState(), scramble));
  if (r && r.every((j) => j.moves >= 1 && j.moves <= 4) && r.reduce((n, j) => n + j.moves, 0) <= 11) first = { scramble, jobs: r.map((j) => j.alg) };
}
// second block: the left block done, the rest mixed by R r U M only
let second: { scramble: string; jobs: string[] } | null = null;
for (let t = 0; t < 400 && !second; t++) {
  const scramble = randomSecondBlockScramble(24);
  const r = solveInStages(SECOND_BLOCK_PLAN, applyAlg(solvedState(), scramble));
  if (r && r.every((j) => j.moves >= 1 && j.moves <= 5) && r.reduce((n, j) => n + j.moves, 0) <= 11) second = { scramble, jobs: r.map((j) => j.alg) };
}
if (!first || !second) throw new Error("no example found");
console.log(`// Generated by scripts/gen-block-examples.ts with the real engine; scripts/test-block-examples.ts checks every line again.`);
console.log(`// "scramble" is done on a solved cube held the usual way. "jobs" are the moves of each small job, in order.`);
console.log(`export const FIRST_BLOCK_EXAMPLE = ${JSON.stringify(first, null, 2)} as const;`);
console.log(`/** the left block is already done; the rest is mixed with R, r, U and M only */`);
console.log(`export const SECOND_BLOCK_EXAMPLE = ${JSON.stringify(second, null, 2)} as const;`);
